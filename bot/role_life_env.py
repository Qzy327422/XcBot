def build_day_context(date_str: str, tz_name: str = "Asia/Shanghai") -> str:
    """仅本地推算星期、工作日/周末、季节与常见节日，绝不联网。"""
    text = str(date_str or "").strip()[:10]
    try:
        parsed = _date.fromisoformat(text)
    except ValueError:
        return ""
    weekday_idx = parsed.weekday()
    weekday_text = _WEEKDAYS[weekday_idx]
    month = parsed.month
    if month in (3, 4, 5):
        season = "春季"
    elif month in (6, 7, 8):
        season = "夏季"
    elif month in (9, 10, 11):
        season = "秋季"
    else:
        season = "冬季"

    tags: list[str] = []
    trad = _TRADITIONAL_HOLIDAYS.get(text)
    solar = _SOLAR_HOLIDAYS.get(text[5:])
    if trad:
        tags.append(trad)
    if solar and solar not in tags:
        tags.append(solar)
    if not tags:
        tags.append("周末" if weekday_idx >= 5 else "工作日")
    return f"{text} {weekday_text}（{' / '.join(tags)}），{season}"
